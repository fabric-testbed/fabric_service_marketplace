"""
Generates the Flask app a service author runs on their node. It has the same
four parts as the reference example service_node/example_app.py: setup, a
/health endpoint, an optional FABRIC token check, and one route per widget that
reads the widget's input fields and returns its output fields (to fill in).
Website links have no node app.
"""
import keyword
import re


# Placeholders filled in by generate_flask_template()
_APP_HEADER = '''\
"""
FABRIC service app, generated by the FABRIC Service Portal.
Run it on your slice VM (with FABnetv6 attached):

    pip install flask requests
    python app.py

The file has four parts:

  1. Setup                              keep
  2. Health check (GET /health)         keep: lets anyone check that your app is running
  3. FABRIC token check                 OPTIONAL: set CHECK_FABRIC_TOKEN = False to turn it off
  4. Your endpoints                     FILL IN: the parts marked  >>> FILL IN <<<

Users can call your app through the portal, or directly from their own slice
VMs on FABnetv6:
    curl -H "Authorization: Bearer $FABRIC_TOKEN" http://[<node ipv6>]:__PORT__/...
"""
import base64
import json
import os
import time
from functools import wraps

import requests
from flask import Flask, g, jsonify, request


# ═══ 1. Setup (keep) ═════════════════════════════════════════════════════════

app = Flask(__name__)


# ═══ 2. Health check (keep) ══════════════════════════════════════════════════
# Answers without a token, so the portal, you or a monitoring tool can check
# that the app is running. Keep it fast and don't return private data.

@app.route("/health")
def health():
    return jsonify({"status": "ok"})


# ═══ 3. FABRIC token check (OPTIONAL) ════════════════════════════════════════
# Your node's FABnetv6 address can be reached from any FABRIC slice, not only
# through the portal. The portal already checks users before forwarding their
# requests, but direct callers skip the portal.
#
# With the check ON, only FABRIC users in your allowed projects can call your
# endpoints, from the portal or directly, and caller() tells you reliably who
# they are (e.g. to record who used what).
#
# With the check OFF, anyone on FABnetv6 can call your endpoints. caller() then
# reads the X-Fabric-User-* headers the portal adds: fine for display, but a
# direct caller can send any values. Turn it off only if that is acceptable.

CHECK_FABRIC_TOKEN = True
# Users must belong to at least one of these FABRIC projects (empty = any FABRIC user)
ALLOWED_PROJECTS = __ALLOWED_PROJECTS__
FABRIC_UIS_URL = os.environ.get("FABRIC_UIS_URL", "https://uis.fabric-testbed.net").rstrip("/")
# Only "service" tokens are accepted: a "resource" token can create and delete
# slices as the user, so users should never send one to a service.
REQUIRED_SCOPE = "service"
_cache = {}  # token -> (expires_at, user); avoids asking FABRIC on every request


def token_scope(token):
    """The token's "scope" claim. Its signature is checked by FABRIC in fabric_user()."""
    try:
        p = token.split(".")[1]
        return json.loads(base64.urlsafe_b64decode(p + "=" * (-len(p) % 4))).get("scope")
    except (IndexError, ValueError, AttributeError):
        return None


def fabric_user(token):
    """Ask FABRIC who owns this token and which projects they are in. None if invalid."""
    hit = _cache.get(token)
    if hit and hit[0] > time.time():
        return hit[1]
    headers = {"Authorization": f"Bearer {token}", "Accept": "application/json"}
    try:
        who = requests.get(f"{FABRIC_UIS_URL}/whoami", headers=headers, timeout=10)
        if who.status_code != 200:
            return None
        me = who.json()["results"][0]
        people = requests.get(f"{FABRIC_UIS_URL}/people/{me['uuid']}?as_self=false",
                              headers=headers, timeout=10)
        if people.status_code != 200:
            return None
        roles = people.json()["results"][0].get("roles") or []
    except (requests.RequestException, KeyError, IndexError, ValueError):
        return None
    # Role names look like "<project-uuid>-pm" / "<project-uuid>-po"
    projects = {r["name"][:-3] for r in roles if r.get("name", "").endswith(("-pm", "-po"))}
    user = {"uuid": me["uuid"], "name": me.get("name"), "projects": projects}
    _cache[token] = (time.time() + 300, user)
    return user


def require_auth(f):
    """With the check on: refuse requests without a valid FABRIC service token
    from an allowed project. With it off: let every request through."""
    @wraps(f)
    def decorated(*args, **kwargs):
        g.user = None
        if not CHECK_FABRIC_TOKEN:
            return f(*args, **kwargs)
        auth = request.headers.get("Authorization", "")
        if not auth.startswith("Bearer "):
            return jsonify({"error": "Missing FABRIC token"}), 401
        token = auth[len("Bearer "):].strip()
        if token_scope(token) != REQUIRED_SCOPE:
            return jsonify({"error": "Please use a FABRIC service token"}), 401
        user = fabric_user(token)
        if not user:
            return jsonify({"error": "Invalid or expired FABRIC token"}), 401
        if ALLOWED_PROJECTS and not (user["projects"] & ALLOWED_PROJECTS):
            return jsonify({"error": "Not a member of an allowed project"}), 403
        g.user = user
        return f(*args, **kwargs)
    return decorated


def caller():
    """Who made this request.
    Check on: verified with FABRIC. Check off: from the portal's X-Fabric-User-*
    headers (None for direct calls, and a direct caller can fake them)."""
    if g.get("user"):
        return {"uuid": g.user["uuid"], "name": g.user["name"], "verified": True}
    return {"uuid": request.headers.get("X-Fabric-User-Uuid"),
            "name": request.headers.get("X-Fabric-User-Name"), "verified": False}


# ═══ 4. Your endpoints (FILL IN) ═════════════════════════════════════════════
# One route per widget on the registration form. Whatever JSON you return is
# shown to the user. @require_auth applies the token check from part 3 (it does
# nothing when the check is off).
'''


def _build_return(output_fields):
    """Build a return jsonify({...}) statement from the widget's output fields."""
    lines = ['    return jsonify({']
    if output_fields:
        for of_ in output_fields:
            lines.append(f'        "{of_["key"]}": "TODO",  # >>> FILL IN <<<  {of_.get("label", "")}')
    else:
        lines.append('        "status": "ok",')
        lines.append('        "caller": caller(),')
    lines.append('    })')
    return '\n'.join(lines)


def _route_body(method, input_fields, output_fields):
    lines = []
    if input_fields:
        where = 'JSON body' if method == 'POST' else 'query parameters'
        lines.append(f"    # The user's form inputs ({where})")
        for field in input_fields:
            fname = field['name']
            if method == 'POST':
                lines.append(f'    {fname} = (request.get_json(silent=True) or {{}}).get("{fname}")')
            else:
                lines.append(f'    {fname} = request.args.get("{fname}")')
        lines.append('')

    lines.append("    # >>> FILL IN: your service's logic <<<")
    lines.append('    # e.g. run a command with subprocess.run([...]) or call another local API.')
    lines.append('    # caller() tells you which FABRIC user made the request.')
    lines.append('')
    lines.append(_build_return(output_fields))
    return '\n'.join(lines)


def _func_name(path):
    """A valid Python function name for a route path, e.g. /v1/2d-scan -> endpoint_v1_2d_scan."""
    name = re.sub(r'[^0-9A-Za-z_]', '_', path.strip('/')).strip('_') or 'root'
    return name if name[0].isalpha() and not keyword.iskeyword(name) else f'endpoint_{name}'


def generate_flask_template(widgets, node_port, allowed_projects=()):
    projects = '{' + ', '.join(repr(p) for p in sorted(allowed_projects)) + '}' if allowed_projects else 'set()'
    header = (_APP_HEADER.replace('__ALLOWED_PROJECTS__', projects)
              .replace('__PORT__', str(node_port)))
    lines = [header]

    # 'health' is taken by the /health route; registration refuses that endpoint
    seen_funcs = {'health'}
    for widget in widgets:
        path = widget['endpoint']
        method = widget['method']
        func_name = _func_name(path)
        if func_name in seen_funcs:
            continue
        seen_funcs.add(func_name)

        lines.append(f"@app.route('{path}', methods=['{method}'])")
        lines.append('@require_auth')
        lines.append(f'def {func_name}():')
        if widget.get('label'):
            lines.append(f'    """{widget["label"]}"""')
        lines.append(_route_body(method, widget.get('input_fields', []),
                                 widget.get('output_fields', [])))
        lines.append('')
        lines.append('')

    lines.append("if __name__ == '__main__':")
    lines.append(f"    app.run(host='::', port={node_port})")
    lines.append('')
    return '\n'.join(lines)
